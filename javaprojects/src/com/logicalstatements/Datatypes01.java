package com.logicalstatements;

public class Datatypes01 {

	byte b;
	short s;
	int i;
	long l;

	float f;
	double d;

	char c;
	boolean boo;

	public static void main(String[] args) {

		System.out.println("MAIN METHOD STATED ");
		Datatypes01 d1 = new Datatypes01();

		System.out.println("Byte value " + d1.b);
		System.out.println("Short value " + d1.s);
		System.out.println("Int value " + d1.i);
		System.out.println("Float value " + d1.l);
		System.out.println("Double value " + d1.f);
		System.out.println("Character value " + d1.d);
		System.out.println("Boolean value " + d1.c);
		System.out.println(d1.boo);

		System.out.println("MAIN METHOD ENDED ");

	}

}
